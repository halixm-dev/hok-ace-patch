// Write astcenc's static tables as Rust source (rust/hokace/astcenc/src/tables.rs) and the unpacked 2D
// percentile tables as little-endian f32 (percentile.bin), and weight_align's sin and cos tables (sincos.bin: sin then
// cos, [64][32] f32 each, from the scalar build's own sinf/cosf), from the sdist's own sources.
//   tables_dump.exe <tables.rs> <percentile.bin> <sincos.bin>
#include "astcenc_internal.h"
#include <cstdio>
// Included, not linked, for its file-local tables.
#include "astcenc_integer_sequence.cpp"
#include "astcenc_weight_align.cpp"

static void u8_row(FILE* f, const uint8_t* p, unsigned n) {
	fprintf(f, "[");
	for (unsigned i = 0; i < n; i++) fprintf(f, "%s%u", i ? "," : "", p[i]);
	fprintf(f, "]");
}

int main(int argc, char** argv) {
	if (argc != 4) return 2;
	FILE* f = fopen(argv[1], "wb");
	fprintf(f, "//! Generated by rust/harness/astcenc_oracle/tables_dump.cpp from astcenc 631fb04e1c4b; do not edit.\n\n");
	fprintf(f, "pub static COLOR_UNQUANT_TO_UQUANT: [[u8; 512]; 17] = [\n");
	for (int q = 0; q < 17; q++) { u8_row(f, color_unquant_to_uquant_tables[q], 512); fprintf(f, ",\n"); }
	fprintf(f, "];\n\npub static COLOR_UQUANT_TO_SCRAMBLED_PQUANT: [[u8; 256]; 17] = [\n");
	for (int q = 0; q < 17; q++) { u8_row(f, color_uquant_to_scrambled_pquant_tables[q], 256); fprintf(f, ",\n"); }
	fprintf(f, "];\n\npub static COLOR_SCRAMBLED_PQUANT_TO_UQUANT: [&[u8]; 17] = [\n");
	for (int q = 0; q < 17; q++) {
		fprintf(f, "&");
		u8_row(f, color_scrambled_pquant_to_uquant_tables[q], get_quant_level(static_cast<quant_method>(q + QUANT_6)));
		fprintf(f, ",\n");
	}
	fprintf(f, "];\n\npub static QUANT_MODE_TABLE: [[i8; 128]; 10] = [\n");
	for (int i = 0; i < 10; i++) {
		fprintf(f, "[");
		for (int j = 0; j < 128; j++) fprintf(f, "%s%d", j ? "," : "", quant_mode_table[i][j]);
		fprintf(f, "],\n");
	}
	fprintf(f, "];\n\npub struct QuantAndTransferTable {\n    pub quant_to_unquant: [u8; 32],\n    pub scramble_map: [u8; 32],\n"
	           "    pub unscramble_and_unquant_map: [u8; 32],\n    pub prev_next_values: [u16; 65],\n}\n\n");
	fprintf(f, "pub static QUANT_AND_XFER_TABLES: [QuantAndTransferTable; 12] = [\n");
	for (int i = 0; i < 12; i++) {
		const quant_and_transfer_table& t = quant_and_xfer_tables[i];
		fprintf(f, "QuantAndTransferTable { quant_to_unquant: "); u8_row(f, t.quant_to_unquant, 32);
		fprintf(f, ", scramble_map: "); u8_row(f, t.scramble_map, 32);
		fprintf(f, ", unscramble_and_unquant_map: "); u8_row(f, t.unscramble_and_unquant_map, 32);
		fprintf(f, ", prev_next_values: [");
		for (int j = 0; j < 65; j++) fprintf(f, "%s%u", j ? "," : "", t.prev_next_values[j]);
		fprintf(f, "] },\n");
	}
	fprintf(f, "];\n\npub static INTEGER_OF_TRITS: [u8; 243] = ");
	u8_row(f, &integer_of_trits[0][0][0][0][0], 243);
	fprintf(f, ";\n\npub static INTEGER_OF_QUINTS: [u8; 125] = ");
	u8_row(f, &integer_of_quints[0][0][0], 125);
	fprintf(f, ";\n\npub static TRITS_OF_INTEGER: [[u8; 5]; 256] = [");
	for (int i = 0; i < 256; i++) { u8_row(f, trits_of_integer[i], 5); fprintf(f, ","); }
	fprintf(f, "];\n\npub static QUINTS_OF_INTEGER: [[u8; 3]; 128] = [");
	for (int i = 0; i < 128; i++) { u8_row(f, quints_of_integer[i], 3); fprintf(f, ","); }
	fprintf(f, "];\n");
	fclose(f);

	static const unsigned sizes[14][2] = {{4,4},{5,4},{5,5},{6,5},{6,6},{8,5},{8,6},{8,8},{10,5},{10,6},{10,8},{10,10},{12,10},{12,12}};
	FILE* b = fopen(argv[2], "wb");
	for (auto& s : sizes) {
		const float* t = get_2d_percentile_table(s[0], s[1]);
		fwrite(t, sizeof(float), WEIGHTS_MAX_BLOCK_MODES, b);
		delete[] t;
	}
	fclose(b);

	prepare_angular_tables();
	FILE* sc = fopen(argv[3], "wb");
	fwrite(sin_table, sizeof(float), SINCOS_STEPS * ANGULAR_STEPS, sc);
	fwrite(cos_table, sizeof(float), SINCOS_STEPS * ANGULAR_STEPS, sc);
	fclose(sc);
	return 0;
}
