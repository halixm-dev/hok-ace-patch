package dev.halixm.hokacepatcher

import android.content.Context
import java.io.File
import java.security.MessageDigest
import org.json.JSONObject

/** Verify the consumed resource manifest before making a runtime directory visible. */
object EngineAssets {
    /** Full installed APK bytes include DEX/coordinator, Chaquopy bridge and native wheels.
     * No VERSION/engine-manifest-only fallback: null means ordinary work without reuse.
     * Recompute after restart; caller must keep the returned producer immutable per attempt.
     */
    fun producerIdentity(context: Context): JSONObject? = runCatching {
        synchronized(this) { producerLocked(context) }
    }.getOrNull()

    private fun producerLocked(context: Context): JSONObject {
        val root = prepare(context)
        val manifestBytes = context.assets.open("engine/manifest.json").use { it.readBytes() }
        val manifest = ArtifactReceipts.parse(manifestBytes)
        check(manifest.getInt("schema") == 1 && manifest.has("producer_inputs"))
        val info = context.applicationInfo
        val apks = JSONObject().put("base.apk", ArtifactReceipts.fileIdentity(File(info.sourceDir)))
        val splits = info.splitSourceDirs.orEmpty().map { ArtifactReceipts.fileIdentity(File(it)) }
            .sortedBy { it.getString("sha256") }
        splits.forEachIndexed { index, identity -> apks.put("split_$index.apk", identity) }
        val native = File(info.nativeLibraryDir)
        val nativeIdentity = if (native.isDirectory) ArtifactReceipts.treeManifest(native)
            else JSONObject().put("packaged_in_apks", true)
        val engine = JSONObject().put("manifest_sha256", ArtifactReceipts.digest(manifestBytes))
            .put("files_key", ArtifactReceipts.identityKey(ArtifactReceipts.treeManifest(root)))
        return JSONObject().put("schema", 1).put("complete", true).put("kind", "android")
            .put("components", JSONObject().put("installed_apks", apks).put("engine", engine)
                .put("native", nativeIdentity).put("abi", org.json.JSONArray(android.os.Build.SUPPORTED_ABIS.toList())))
    }

    private val DIGEST = Regex("[0-9a-f]{64}")

    /** The engine folder name [prepare] uses: the sha256 of this APK's `engine/manifest.json`. */
    private fun manifestDigest(manifestBytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(manifestBytes).joinToString("") { "%02x".format(it) }

    /**
     * The `engine/<digest>` folders an earlier app build extracted (about 56 MB each) that may go: a real
     * directory (never a link) named by a digest other than <current>, not in <keep> (every digest a pending
     * run, unresolved session or first setup still names), and holding no live link's target (<linkTargets>,
     * canonical paths). Anything else under `engine/` stays. Null when the folder cannot be listed, so an
     * unreadable tree deletes nothing.
     */
    internal fun staleFolders(engineRoot: File, current: String, keep: Set<String>, linkTargets: List<String>): List<File>? {
        require(DIGEST.matches(current)) { "Invalid engine identity" }
        if (!engineRoot.exists() && !java.nio.file.Files.isSymbolicLink(engineRoot.toPath())) return emptyList()
        if (java.nio.file.Files.isSymbolicLink(engineRoot.toPath()) || !engineRoot.isDirectory) return null
        val children = engineRoot.listFiles() ?: return null
        return children.filter { child ->
            val path = child.toPath()
            child.name != current && child.name !in keep && DIGEST.matches(child.name) &&
                !java.nio.file.Files.isSymbolicLink(path) && child.isDirectory &&
                child.canonicalPath.let { folder -> linkTargets.none { it == folder || it.startsWith(folder + File.separator) } }
        }.sortedBy { it.name }
    }

    /**
     * Measured-shortage reclaim (coordinator lock held): delete [staleFolders]. Serialized with [prepare], so
     * the current folder is never measured half-cleaned; the current digest is never a candidate. Returns
     * the bytes freed.
     */
    @Synchronized fun releaseStale(context: Context, keep: Set<String>, linkTargets: List<String>): Long {
        val current = context.assets.open("engine/manifest.json").use { manifestDigest(it.readBytes()) }
        val stale = staleFolders(File(context.filesDir.canonicalFile, "engine"), current, keep, linkTargets) ?: return 0L
        var freed = 0L
        for (folder in stale) freed += DurableFiles.deleteTree(folder)
        return freed
    }

    /** Generated by an interpreter or by an interrupted [prepare], never shipped: Python bytecode caches. */
    internal const val BYTECODE_CACHE = "__pycache__"

    /**
     * Remove what earlier app versions generated inside the engine folder and the manifest never lists:
     * `__pycache__` folders (Python wrote them on import until the bridge set `dont_write_bytecode`) and
     * `.partial` copies of an interrupted extraction. These are proven generated outputs, not engine content;
     * left in place they would be measured into `files_key`, and stale bytecode would run in place of the
     * verified source. Anything else unlisted stays, and is measured honestly. Returns the removed paths.
     */
    internal fun removeGenerated(root: File, listed: Set<String>): List<String> {
        val removed = mutableListOf<String>()
        fun visit(directory: File) {
            for (child in directory.listFiles().orEmpty().sortedBy { it.name }) {
                val relative = child.relativeTo(root).invariantSeparatorsPath
                check(!java.nio.file.Files.isSymbolicLink(child.toPath())) { "Linked resource path" }
                when {
                    child.isDirectory && child.name == BYTECODE_CACHE -> {
                        check(listed.none { it.startsWith("$relative/") }) { "Listed bytecode cache: $relative" }
                        // Python writes only flat .pyc files here; anything else is not proven generated.
                        for (item in child.listFiles().orEmpty().sortedBy { it.name }) {
                            check(!java.nio.file.Files.isSymbolicLink(item.toPath()) && item.isFile &&
                                (item.name.endsWith(".pyc") || item.name.contains(".pyc."))) {
                                "Unexpected item in bytecode cache: $relative/${item.name}"
                            }
                            check(item.delete() || !item.exists()) { "Cannot remove generated bytecode: $relative" }
                            removed += "$relative/${item.name}"
                        }
                        check(child.delete() || !child.exists()) { "Cannot remove generated bytecode: $relative" }
                    }
                    child.isDirectory -> visit(child)
                    child.isFile && child.name.endsWith(".partial") && relative !in listed -> {
                        check(child.delete() || !child.exists()) { "Cannot remove interrupted resource: $relative" }
                        removed += relative
                    }
                }
            }
        }
        visit(root)
        return removed
    }

    /**
     * Verify (and extract where needed) the engine folder for this APK's manifest. Serialized in-process, so a
     * concurrent [producerIdentity] never measures a half-extracted or half-cleaned folder.
     */
    @Synchronized fun prepare(context: Context): File {
        val manifestBytes = context.assets.open("engine/manifest.json").use { it.readBytes() }
        val digest = manifestDigest(manifestBytes)
        // Android's trusted filesDir may itself use /data/user/0 -> /data/data.
        // Canonicalize that boundary only; descendants must never be redirected.
        val root = File(context.filesDir.canonicalFile, "engine/$digest")
        val files = JSONObject(String(manifestBytes, Charsets.UTF_8)).getJSONObject("files")
        check(root.canonicalFile.toPath() == root.toPath().toAbsolutePath().normalize()) { "Linked engine path" }
        root.mkdirs()
        ArtifactReceipts.safe(root, true)
        check(files.length() <= 100000) { "Too many resource files" }
        val removed = removeGenerated(root, files.keys().asSequence().toSet())
        if (removed.isNotEmpty()) DiagnosticTrace.event("engine", "Removed ${removed.size} generated files from the engine folder")
        for (name in files.keys()) {
            ArtifactReceipts.relativePath(name)
            val target = File(root, name)
            val expected = files.getString(name)
            check(Regex("[0-9a-f]{64}").matches(expected)) { "Invalid resource digest" }
            // Canonical checks also cover nonexistent targets beneath linked ancestors.
            check(target.canonicalFile.toPath() == target.toPath().toAbsolutePath().normalize()) { "Linked resource path" }
            fun hash(file: File): String {
                val md = MessageDigest.getInstance("SHA-256")
                file.inputStream().use { stream ->
                    val buffer = ByteArray(1024 * 1024)
                    while (true) {
                        val count = stream.read(buffer)
                        if (count < 0) break
                        md.update(buffer, 0, count)
                    }
                }
                return md.digest().joinToString("") { "%02x".format(it) }
            }
            if (target.isFile && hash(target) == expected) continue
            target.parentFile!!.mkdirs()
            val temp = File(target.parentFile, target.name + ".partial")
            context.assets.open("engine/$name.payload").use { source -> temp.outputStream().use { source.copyTo(it) } }
            check(hash(temp) == expected) { "Resource digest mismatch: $name" }
            if (target.exists()) check(target.delete()) { "Cannot replace invalid resource: $name" }
            check(temp.renameTo(target)) { "Cannot install resource: $name" }
            check(target.setReadOnly()) { "Cannot protect resource: $name" }
        }
        return root
    }
}
